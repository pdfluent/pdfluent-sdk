"""render_homebrew_formula.py — generate Formula/pdfluent.rb, never edit by hand.

The formula points on_macos/on_linux x on_arm/on_intel at the four macOS and
glibc CLI release archives, with their sha256 taken from SHA256SUMS. It
refuses (exit 1, naming the platform) when a platform is missing from
SHA256SUMS, so a partial release set can never produce a formula that installs
on three platforms and 404s on the fourth.

Usage:
  python3 scripts/release/render_homebrew_formula.py --version 1.0.0 \
      --sums dist/cli/SHA256SUMS --out Formula/pdfluent.rb
  python3 scripts/release/render_homebrew_formula.py --version 1.0.0 \
      --sums dist/cli/SHA256SUMS --brew-audit   # render + brew audit --strict

--brew-audit runs `brew audit --strict` over the rendered formula and exits
with its status. It needs brew on PATH (the operator Mac, not Linux CI).

Pushing the formula to pdfluent/homebrew-tap is manual, and creating that
repository is Jasper's decision (account-visible).

Tests: scripts/release/test_render_homebrew_formula.py.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# The four archives Homebrew serves: (formula os, formula arch, triple).
HOMEBREW_TARGETS: tuple[tuple[str, str, str], ...] = (
    ("macos", "arm", "aarch64-apple-darwin"),
    ("macos", "intel", "x86_64-apple-darwin"),
    ("linux", "arm", "aarch64-unknown-linux-gnu"),
    ("linux", "intel", "x86_64-unknown-linux-gnu"),
)

PLATFORM_OF_TRIPLE = {
    "aarch64-apple-darwin": "macos-arm64",
    "x86_64-apple-darwin": "macos-x64",
    "aarch64-unknown-linux-gnu": "linux-arm64",
    "x86_64-unknown-linux-gnu": "linux-x64",
}

FIXTURE_SENTENCE = "The homebrew sky is clear."

# A minimal one-page PDF carrying FIXTURE_SENTENCE, verified to extract
# through the engine (extract-text returns the sentence, exit 0). Pure ASCII
# so it embeds verbatim in the formula's test block.
FIXTURE_PDF = """%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>
endobj
4 0 obj
<< /Length 57 >>
stream
BT /F1 24 Tf 72 720 Td (The homebrew sky is clear.) Tj ET
endstream
endobj
5 0 obj
<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>
endobj
xref
0 6
0000000000 65535 f
0000000009 00000 n
0000000058 00000 n
0000000115 00000 n
0000000241 00000 n
0000000348 00000 n
trailer
<< /Size 6 /Root 1 0 R >>
startxref
418
%%EOF
"""


class MissingPlatform(Exception):
    def __init__(self, platform: str, archive: str):
        super().__init__(
            f"SHA256SUMS misses platform {platform} ({archive})"
        )
        self.platform = platform
        self.archive = archive


def parse_sums(sums_path: Path) -> dict[str, str]:
    entries: dict[str, str] = {}
    for line in sums_path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2:
            continue
        digest, name = parts
        entries[name.removeprefix("*")] = digest
    return entries


def archive_name(version: str, triple: str) -> str:
    return f"pdfluent-{version}-{triple}.tar.gz"


def render(version: str, sums: dict[str, str], repo: str) -> str:
    """Render the formula. Raises MissingPlatform naming the gap."""
    blocks: dict[str, dict[str, tuple[str, str]]] = {
        "macos": {},
        "linux": {},
    }
    for os_name, arch, triple in HOMEBREW_TARGETS:
        name = archive_name(version, triple)
        if name not in sums:
            raise MissingPlatform(PLATFORM_OF_TRIPLE[triple], name)
        url = f"https://github.com/{repo}/releases/download/v{version}/{name}"
        blocks[os_name][arch] = (url, sums[name])

    def on_arch(os_name: str) -> str:
        out = []
        for arch in ("arm", "intel"):
            url, digest = blocks[os_name][arch]
            out.append(f"    on_{arch} do")
            out.append(f'      url "{url}"')
            out.append(f'      sha256 "{digest}"')
            out.append("    end")
        return "\n".join(out)

    return f"""# Generated by scripts/release/render_homebrew_formula.py -- DO NOT EDIT.
# pdfluent {version}, from {repo} releases.
class Pdfluent < Formula
  desc "PDF text extraction for pipelines (markdown, JSON, chunks)"
  homepage "https://pdfluent.com"
  version "{version}"
  # AGPL-3.0-only here; a commercial licence is available, see
  # https://pdfluent.com/sdk/pricing
  license "AGPL-3.0-only"

  on_macos do
{on_arch("macos")}
  end

  on_linux do
{on_arch("linux")}
  end

  def install
    bin.install "pdfluent"
    man1.install Dir["man/man1/*.1"]
    doc.install "README.md"
    (doc/"licenses").install "LICENSE", "LICENSE-COMMERCIAL", "NOTICE",
      "THIRD_PARTY_LICENSES.txt"
  end

  test do
    system bin/"pdfluent", "--version"
    (testpath/"brew_fixture.pdf").write <<~EOS
{FIXTURE_PDF}    EOS
    out = shell_output("#{{bin}}/pdfluent extract #{{testpath}}/brew_fixture.pdf --format markdown")
    assert_match "{FIXTURE_SENTENCE}", out
  end
end
"""


def run_brew_audit(formula: Path) -> int:
    """Run `brew audit --strict` over the formula. Returns its exit code.

    Exit 2 when brew is not on PATH: the audit runs on the operator Mac, and
    "no brew" must not read as "audit passed".
    """
    if shutil.which("brew") is None:
        print("render-homebrew-formula: need `brew` on PATH for --brew-audit",
              file=sys.stderr)
        return 2
    proc = subprocess.run(["brew", "audit", "--strict", str(formula)])
    return proc.returncode


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Render the pdfluent Homebrew formula from SHA256SUMS."
    )
    ap.add_argument("--version", required=True, help="release version")
    ap.add_argument("--sums", type=Path, required=True, help="SHA256SUMS file")
    ap.add_argument("--repo", default="pdfluent/engine",
                    help="GitHub repo holding the release archives")
    ap.add_argument("--out", type=Path, help="write the formula here "
                    "(default: stdout)")
    ap.add_argument("--brew-audit", action="store_true",
                    help="run `brew audit --strict` over the rendered formula")
    args = ap.parse_args(argv)

    if not args.sums.is_file():
        print(f"render-homebrew-formula: no SHA256SUMS at {args.sums}",
              file=sys.stderr)
        return 1
    try:
        text = render(args.version, parse_sums(args.sums), args.repo)
    except MissingPlatform as e:
        print(f"render-homebrew-formula: {e}", file=sys.stderr)
        return 1

    if args.out is not None:
        args.out.write_text(text)
        print(f"render-homebrew-formula: wrote {args.out}")
        formula_path = args.out
    else:
        print(text, end="")
        formula_path = None

    if args.brew_audit:
        if formula_path is None:
            with tempfile.NamedTemporaryFile(
                "w", suffix=".rb", prefix="pdfluent-", delete=False
            ) as tmp:
                tmp.write(text)
                formula_path = Path(tmp.name)
        return run_brew_audit(formula_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
