"""No TypeScript reserved word may be a parameter name in the Node typings.

WHAT BREAKS WITHOUT THIS

`crates/pdf-node/index.d.ts` is generated by `napi build` from the Rust
parameter names, verbatim. Three of those were reserved words -- `getEnvBool`
and `getEnvInt` took a parameter called `default`, `updateStream` one called
`new` -- so the published typings did not parse:

    index.d.ts(720,50): error TS1359: Identifier expected. 'default' is a
    reserved word that cannot be used here.

`skipLibCheck` does not save the consumer: it skips type checking of
declaration files, not syntactic errors. Every TypeScript consumer compiling
with `skipLibCheck: false` failed on our typings, and
`integrations/pdfluent-extract-js` failed its `tsc` build outright (desktop
r6b suite `extract_js`, rc 2). The fix renamed the Rust parameters in the
pdf-node binding only (`default_value`, `new_stream`); JavaScript callers
pass positionally, so the runtime behaviour and the `js_name`s are unchanged.

WHAT IS CHECKED

Every parameter name in `crates/pdf-node/index.d.ts` -- and in
`crates/pdf-node/compat.d.ts` when it exists -- against the TypeScript /
JavaScript reserved words. Comments and string literals are masked first, so
a doc line like `DPI (default: 72.0)` is not a parameter; only identifiers
in parameter position -- preceded by `(` or `,` (or `...`), followed by an
optional `?` and `:`, inside `(...)` -- are judged. Object-type properties
(`{ default: boolean }`) are legal TypeScript and are not flagged.

The word list is deliberately the full reserved set, not just what one tsc
version rejects today: probed against tsc 6.0.3, `implements`, `interface`,
`let`, `package`, `private`, `protected` and `public` pass as parameter
names there, but they are reserved words and a later or stricter toolchain
may refuse them. Kept OUT are the names tsc accepts by design: the `this`
parameter, the contextual names (`static`, `eval`, `arguments`, `await`,
`yield`, `type`, `from`, `of`, ...) and the type names (`number`, `string`,
...), all probed green. A guard stricter than every compiler would cry wolf;
a guard looser than one lets a red publish.

FLOOR, because a scan that reads nothing approves everything

`index.d.ts` must exist and parse, and the scan must see at least
MIN_PARAMS parameters across the files. The tree holds over a thousand;
fewer means the walk lost its pattern rather than found a clean tree.

Usage:
    python3 scripts/ci/node_typings_have_no_reserved_parameter.py
    python3 scripts/ci/node_typings_have_no_reserved_parameter.py --self-test

Exit codes:
    0  no reserved-word parameter, and the floor holds (--self-test: all cases pass)
    1  a reserved-word parameter is named, the floor is breached, or a self-test case fails
"""
from __future__ import annotations

import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
INDEX_DTS = REPO / "crates" / "pdf-node" / "index.d.ts"
COMPAT_DTS = REPO / "crates" / "pdf-node" / "compat.d.ts"

# The ECMAScript keywords, the future reserved words and the strict-mode
# reserved words. `this` is excluded on purpose: a leading `this` parameter
# is the documented this-type annotation, not an accident. Contextual names
# (static, eval, arguments, await, yield, type, from, of, ...) and type
# names (number, string, ...) are legal parameter names -- probed green
# against tsc -- and are excluded so the guard cannot cry wolf.
RESERVED = frozenset({
    "break", "case", "catch", "class", "const", "continue", "debugger",
    "default", "delete", "do", "else", "enum", "export", "extends",
    "false", "finally", "for", "function", "if", "implements", "import",
    "in", "instanceof", "interface", "let", "new", "null", "package",
    "private", "protected", "public", "return", "super", "switch",
    "throw", "true", "try", "typeof", "var", "void", "while", "with",
})

# An identifier in parameter position: after `(` or `,` (rest args after
# `...`), before an optional `?` and the type colon.
PARAM_RX = re.compile(r"[(,]\s*(?:\.\.\.\s*)?([A-Za-z_$][\w$]*)\s*\??\s*:")

MIN_PARAMS = 100

TAG = "node-dts-reserved"


def mask_strings_and_comments(src: str) -> str:
    """Blank strings and comments, keeping newlines and offsets.

    A doc line like `/** DPI (default: 72.0). */` holds `(default:` -- the
    parameter shape -- and would be a finding if comments were scanned.
    """
    out = list(src)
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c in "'\"`":
            j = i + 1
            while j < n:
                if src[j] == "\\":
                    j += 2
                    continue
                if src[j] == c:
                    j += 1
                    break
                j += 1
            for k in range(i, min(j, n)):
                if out[k] != "\n":
                    out[k] = " "
            i = j
        elif c == "/" and i + 1 < n and src[i + 1] == "/":
            j = src.find("\n", i)
            if j < 0:
                j = n
            for k in range(i, j):
                out[k] = " "
            i = j
        elif c == "/" and i + 1 < n and src[i + 1] == "*":
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            for k in range(i, j):
                if out[k] != "\n":
                    out[k] = " "
            i = j
        else:
            i += 1
    return "".join(out)


def innermost_bracket(masked: str) -> list[str]:
    """The innermost enclosing bracket at each offset ('', '(' or '[' or '{')."""
    encloser: list[str] = []
    stack: list[str] = []
    for ch in masked:
        encloser.append(stack[-1] if stack else "")
        if ch in "([{":
            stack.append(ch)
        elif ch in ")]}" and stack:
            stack.pop()
    return encloser


def parameters(masked: str) -> list[tuple[str, int]]:
    """(name, offset) of every parameter in masked declaration text."""
    encloser = innermost_bracket(masked)
    found: list[tuple[str, int]] = []
    for match in PARAM_RX.finditer(masked):
        # Inside `(...)` it is a parameter (or a tuple label, which obeys
        # the same rule); inside `{...}` it is an object property, which
        # may legally carry a reserved name.
        if encloser[match.start(1)] in "([":
            found.append((match.group(1), match.start(1)))
    return found


def line_of(src: str, offset: int) -> int:
    return src.count("\n", 0, offset) + 1


def display(path: pathlib.Path) -> str:
    try:
        return str(path.relative_to(REPO))
    except ValueError:
        return str(path)


def judge(files: list[pathlib.Path]) -> tuple[list[str], int]:
    findings: list[str] = []
    scanned = 0
    for path in files:
        try:
            src = path.read_text(encoding="utf-8")
        except OSError as why:
            findings.append(f"{display(path)}: could not be read: {why}")
            continue
        masked = mask_strings_and_comments(src)
        params = parameters(masked)
        scanned += len(params)
        if not params:
            findings.append(
                f"{display(path)}: no parameters found; the scan "
                "pattern fits nothing in this file")
            continue
        for name, offset in params:
            if name in RESERVED:
                findings.append(
                    f"{display(path)}:{line_of(src, offset)}: "
                    f"parameter `{name}` is a reserved word")
    return findings, scanned


def target_files() -> list[pathlib.Path]:
    files = [INDEX_DTS]
    if COMPAT_DTS.exists():
        files.append(COMPAT_DTS)
    return files


SELF_TEST_CASES: list[tuple[str, str, list[str]]] = [
    ("reserved default",
     "export declare function getEnvBool(name: string, default: boolean): boolean\n",
     ["default"]),
    ("renamed default is clean",
     "export declare function getEnvBool(name: string, default_value: boolean): boolean\n",
     []),
    ("reserved optional new",
     "  updateStream(xref?: number | null, new?: boolean | null): void\n",
     ["new"]),
    ("comment mentions are not parameters",
     "/** DPI (default: 72.0). */\n// new: something\n"
     "export declare function f(a: string): void\n",
     []),
    ("object properties may carry reserved names",
     "interface O { default: boolean; new?: string }\n"
     "export declare function f(opts: { delete: number }, ok: string): void\n",
     []),
    ("string contents are not parameters",
     'declare const s: "a, new: b";\n'
     "export declare function f(a: string): void\n",
     []),
    ("rest and tuple labels are judged",
     "export declare function f(...args: string[]): void\n"
     "export declare function g(first: string, class: string): void\n",
     ["class"]),
]


def self_test() -> int:
    failures = 0
    for title, fake, want in SELF_TEST_CASES:
        masked = mask_strings_and_comments(fake)
        got = sorted(name for name, _ in parameters(masked) if name in RESERVED)
        if got != sorted(want):
            print(f"[{TAG}] self-test FAIL: {title}: want {want}, got {got}",
                  file=sys.stderr)
            failures += 1
        else:
            print(f"[{TAG}] self-test ok: {title}")
    # The fake that must be red end to end, through judge(), and the floor.
    red = (
        "export declare function getEnvBool(name: string, default: boolean): boolean\n"
        "export declare function getEnvInt(name: string, default: number): number\n"
        "export declare function f(a: string): void\n"
    )
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        probe = pathlib.Path(tmp) / "probe.d.ts"
        probe.write_text(red, encoding="utf-8")
        findings, scanned = judge([probe])
    if len(findings) != 2 or scanned != 5:
        print(f"[{TAG}] self-test FAIL: end-to-end probe: want 2 findings "
              f"over 5 params, got {len(findings)} over {scanned}",
              file=sys.stderr)
        failures += 1
    else:
        print(f"[{TAG}] self-test ok: end-to-end probe red with 2 findings")
    if failures:
        print(f"[{TAG}] self-test FAIL: {failures} case(s) failed", file=sys.stderr)
        return 1
    print(f"[{TAG}] self-test OK: all cases pass")
    return 0


def main() -> int:
    if len(sys.argv) > 1 and sys.argv[1] == "--self-test":
        return self_test()
    if len(sys.argv) > 1:
        print(f"usage: {pathlib.Path(sys.argv[0]).name} [--self-test]",
              file=sys.stderr)
        return 1
    if not INDEX_DTS.exists():
        print(f"[{TAG}] FAIL: {INDEX_DTS.relative_to(REPO)} is not in the tree",
              file=sys.stderr)
        return 1
    files = target_files()
    findings, scanned = judge(files)

    if scanned < MIN_PARAMS:
        print(f"[{TAG}] FAIL: scanned {scanned} parameter(s) across "
              f"{len(files)} file(s); floor is {MIN_PARAMS}. An empty scan "
              "approves everything.", file=sys.stderr)
        return 1

    if findings:
        print(f"[{TAG}] FAIL: reserved words as parameter names in the "
              "published Node typings", file=sys.stderr)
        for line in findings:
            print(f"  - {line}", file=sys.stderr)
        return 1

    print(f"[{TAG}] OK: {scanned} parameter(s) across {len(files)} file(s); "
          "no reserved-word parameter")
    return 0


if __name__ == "__main__":
    sys.exit(main())
