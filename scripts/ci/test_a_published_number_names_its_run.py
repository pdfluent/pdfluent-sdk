"""The published-figure guard has to reject what it claims to reject.

Every case below is a way a number has actually got out of a building without a
measurement behind it: typed into a table by hand, left standing after the run
it came from was replaced, quoted from an axis that never ran, or written into
the prose where no table row could hold it. The tree is built from scratch each
time, the real programme and the real guard are run over it, and the repaired
tree must come back clean -- a guard that fails on everything says as little as
one that fails on nothing.

The programme is copied into the temporary tree rather than imported from the
checkout, because the guard renders the table with the programme it finds NEXT
TO the runs it is judging. That is also what makes this test bite on the
programme: change how a figure is rendered and the fabricated document stops
matching, which is the whole mechanism these cases rest on.

Nothing here touches the real tree.

Exit codes:
    0  the guard behaves
    1  it let something through, or rejected something it should not
"""

