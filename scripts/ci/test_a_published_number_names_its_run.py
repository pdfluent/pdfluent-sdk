def main() -> int:
    failures: list[str] = []

    for description, mutate, reason in CASES:
        with tempfile.TemporaryDirectory() as tmp:
            root = pathlib.Path(tmp)
            build(root)
            mutate(root)
            code, output = run_guard(root)
            caught = code != 0 and (reason is None or reason in output)
            print(f"  {'caught' if caught else 'MISSED':7} exit={code}  {description}")
            if not caught:
                failures.append(description)
                for line in output.strip().splitlines():
                    print(f"          {line}")

    for description, mutate in CLEAN_CASES:
        with tempfile.TemporaryDirectory() as tmp:
            root = pathlib.Path(tmp)
            build(root)
            mutate(root)
            code, output = run_guard(root)
            print(f"  {'clean' if code == 0 else 'FALSE+':7} exit={code}  {description}")
            if code != 0:
                failures.append(description)
                for line in output.strip().splitlines():
                    print(f"          {line}")

    with tempfile.TemporaryDirectory() as tmp:
        root = pathlib.Path(tmp)
        build(root)
        code, output = run_guard(root)
        print(f"  {'clean' if code == 0 else 'FALSE+':7} exit={code}  the repaired tree")
        if code != 0:
            failures.append("the repaired tree is rejected")
            for line in output.strip().splitlines():
                print(f"          {line}")

    if failures:
        print(f"\nFAIL: {len(failures)} case(s): {'; '.join(failures)}")
        return 1
    print(f"\nOK: {len(CASES)} rejections, {len(CLEAN_CASES) + 1} clean trees.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
