"""The budget guard of #598 refuses a model over either number, and one it
cannot read; the real tree passes."""
from __future__ import annotations

import pathlib
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[2]
GUARD = REPO / "scripts" / "ci" / "a_learned_model_stays_in_budget.py"
MARK = "// @generated by scripts/extraction/learned/export_rust.py -- do not edit.\n"


def run(body: str | None = None, files: dict[str, str] | None = None) -> int:
    with tempfile.TemporaryDirectory() as d:
        root = pathlib.Path(d)
        for name, text in (files or {"m.rs": body}).items():
            path = root / "crates" / "x" / "src" / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        return subprocess.run([sys.executable, str(GUARD), "--root", str(root)],
                              capture_output=True, text=True).returncode


def main() -> int:
    fails = []
    small = MARK + "//! The `m` model: 8 trees, 24 splits, depth at most 3.\n"
    if run(small) != 0:
        fails.append("a small model was refused")
    # The owner's numbers of 23-09-2026 (#599): 5 MB and 5,000 per model.
    if run(MARK + "//! The `m` model: 2000 trees, 9000 splits, depth at most 3.\n") != 1:
        fails.append("6000 comparisons per prediction passed")
    if run(small + "// " + "x" * 5_100_000 + "\n") != 1:
        fails.append("5.1 MB of generated code passed")
    # A large model is a directory: mod.rs with the header, part files with the
    # trees. The parts count towards the model, so three parts of 1.8 MB are one
    # model of 5.4 MB, over budget, though every file is under it.
    part = MARK + "//! Trees 0 to 9 of the `m` model.\n// " + "x" * 1_800_000 + "\n"
    chunked = {"m/mod.rs": MARK + "//! The `m` model: 30 trees, 90 splits, depth at most 8, in 3 part(s).\n",
               "m/part_00.rs": part, "m/part_01.rs": part, "m/part_02.rs": part}
    if run(files=chunked) != 1:
        fails.append("a model of three 1.8 MB parts passed as three small files")
    # And ALL models together stay under 25 MB (owner, 28-09-2026): six models
    # of 4.5 MB each, every one within its own budget, are 27 MB of engine --
    # and five of them, 22.5 MB, are inside it.
    six = {f"m{i}.rs": small + "// " + "x" * 4_500_000 + "\n" for i in range(6)}
    if run(files=six) != 1:
        fails.append("27 MB of learned models together passed")
    five = {f"m{i}.rs": small + "// " + "x" * 4_500_000 + "\n" for i in range(5)}
    if run(files=five) != 0:
        fails.append("22.5 MB of learned models together failed, under the 25 MB ceiling")
    if run(MARK + "//! no header here\n") != 1:
        fails.append("a model with no readable header passed")
    if run("// hand-written, not generated\n" + "x" * 5_100_000) != 0:
        fails.append("a file the exporter did not write was judged")
    if subprocess.run([sys.executable, str(GUARD)], capture_output=True).returncode != 0:
        fails.append("the real tree is over budget")
    for f in fails:
        print(f"FAIL: {f}", file=sys.stderr)
    if fails:
        return 1
    print("learned-budget guard: 9 cases, all as expected.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
