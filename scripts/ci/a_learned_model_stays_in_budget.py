"""Every exported model stays inside its size and speed budget (#598).

The promise that stays when decisions become learned is speed: plain Rust, no
runtime, a page as fast as before. So every file export_rust.py generated --
wherever the lane that owns the decision put it -- is held to two numbers:

  MAX_BYTES        2 MB of generated code, the ticket's ceiling.
  MAX_COMPARISONS  2000 comparisons on the longest path of one prediction
                   (trees x depth, from the header the exporter writes). At
                   about a nanosecond each that is 2 µs per block; a page of a
                   hundred blocks pays 0.2 ms per model.

A count and not a stopwatch, on purpose: the lane-time guard of #597 showed
what a timing guard on a shared or pooled machine measures, and a comparison
count is the same on every machine and cannot flake. A model the exporter wrote
without its header is refused too: the budget reads the header.

Exit codes:
  0  every generated model is inside both numbers
  1  one is not, or has no header to read
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
MARK = "@generated by scripts/extraction/learned/export_rust.py"
# A network's weights (#638), sized the same way; it has no trees, so its
# header names parameters instead, and a prediction's cost is its size.
NET_MARK = "@generated by scripts/extraction/learned/export_gnn_rust.py"
HEADER = re.compile(r"(\d+) trees, (\d+) splits, depth at most (\d+)[.,]")
# Raised by the owner on 23-09-2026 (#599): the list models lose 0.04 F1 at 2 MB
# and 2,000, and speed matters more than size. The TOTAL holds every learned
# model in the engine together, because headings and tables are still to come.
# The total raised again by the owner on 28-09-2026, from 15 to 25 MB: the line
# model, the table judge and the list models are all in flight at once. Per
# model the two numbers stay where they were.
MAX_BYTES = 5_000_000
MAX_COMPARISONS = 5000
MAX_TOTAL_BYTES = 25_000_000


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=pathlib.Path, default=REPO)
    args = ap.parse_args()
    problems, seen, total = [], 0, 0
    for path in sorted((args.root / "crates").rglob("*.rs")):
        head = path.read_text(encoding="utf-8", errors="replace")[:4000]
        network = NET_MARK in head
        if MARK not in head and not network:
            continue
        # A large model is a directory: `mod.rs` carries the header and the
        # `part_NN.rs` files beside it carry the trees. It is ONE model, and
        # its size is the directory's.
        if path.name.startswith("part_"):
            continue
        seen += 1
        where = path.relative_to(args.root)
        if path.name == "mod.rs":
            size = sum(p.stat().st_size for p in path.parent.glob("*.rs")
                       if (NET_MARK if network else MARK)
                       in p.read_text(encoding="utf-8", errors="replace")[:4000])
        else:
            size = path.stat().st_size
        total += size
        if size > MAX_BYTES:
            problems.append(f"{where}: {size} bytes of generated code, over {MAX_BYTES}")
        if network:
            continue
        m = HEADER.search(head)
        if not m:
            problems.append(f"{where}: no 'N trees, N splits, depth at most N.' header to read")
            continue
        trees, _splits, depth = (int(g) for g in m.groups())
        if trees * depth > MAX_COMPARISONS:
            problems.append(f"{where}: {trees} trees x depth {depth} = {trees * depth} comparisons "
                            f"per prediction, over {MAX_COMPARISONS}")
    if total > MAX_TOTAL_BYTES:
        problems.append(f"all learned models together: {total} bytes, over {MAX_TOTAL_BYTES}")
    if problems:
        print(f"[learned-budget] FAIL: {len(problems)} model(s) over budget:", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        print("  Fewer or shallower trees, or a decision split in two.", file=sys.stderr)
        return 1
    print(f"[learned-budget] OK: {seen} generated model(s), each under {MAX_BYTES} bytes and "
          f"{MAX_COMPARISONS} comparisons per prediction, {total} bytes together "
          f"(ceiling {MAX_TOTAL_BYTES}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
