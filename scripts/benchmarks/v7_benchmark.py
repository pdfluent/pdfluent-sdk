REPO = pathlib.Path(__file__).resolve().parents[2]

# Where a run lands, and the one document that may publish from it. Both are
# read by the guard; keep them here so there is one spelling of each.
RUNS_DIR = pathlib.Path("benchmarks") / "runs" / "v7"
PUBLISHED = pathlib.Path("benchmarks") / "V7_BENCHMARK_PROGRAMME.md"
REGISTRY = pathlib.Path("benchmarks") / "BASELINE_HARDWARE.toml"
GATE_MANIFEST = pathlib.Path("corpus") / "GATE_CORPUS_MANIFEST.json"

BEGIN = "<!-- MEASURED: generated by scripts/benchmarks/v7_benchmark.py publish -->"
END = "<!-- END MEASURED -->"

# The three axes, in the order they are reported. Fixed: an axis that can be
# renamed by whoever measures next is an axis nobody can compare across runs.
AXES = ("performance", "archiving", "accuracy")

# A run identifier. Every published figure names one of these, and the guard
# resolves it to a file -- so the shape is part of the contract, not a habit.
RUN_ID = re.compile(r"^v7-\d{4}-\d{2}-\d{2}-[a-z0-9][a-z0-9-]*$")

DOCUMENT_SETS = {
    "fixtures": {
        "default_dir": "crates/visual-regression/fixtures",
        "description": "Fixtures generated by this repository for its own "
                       "visual-regression suite.",
        "licence": "AGPL-3.0-only OR LicenseRef-PDFluent-Commercial (ours)",
    },
    "gate-corpus": {
        "default_dir": None,
        "description": "The gate corpus of corpus/GATE_CORPUS_MANIFEST.json, "
                       "fetched at pinned commits by scripts/ci/fetch_gate_corpus.py.",
        "licence": "Apache-2.0 and CC-BY-4.0 (pdf.js, PDFBox, veraPDF corpus)",
    },
}

# Below this many source words the retention figure says nothing and says it at
# 100%. Same rule and same number as the claim register's A12: such documents
# are counted apart, not counted in.
MIN_SOURCE_WORDS = 20


# ---------------------------------------------------------------------------
# The machine, before anything is measured
# ---------------------------------------------------------------------------
def machine_class(repo: pathlib.Path, want: str, observed_cores: int) -> dict:
    """The registry entry for `want`, or exit non-zero saying why not.

    The core count is the identity check. A class that declares twelve cores on
    a machine with ten is either the wrong class or a class that moved under its
    entry; both invalidate every comparison the result would be used for, and
    relabelling the run is the failure #283 exists to stop.
    """
    path = repo / REGISTRY
    if not path.is_file():
        raise SystemExit(f"{path} is missing; nothing can say what this machine is.")
    classes = tomllib.loads(path.read_text()).get("classes", {})
    entry = classes.get(want)
    if entry is None:
        known = ", ".join(sorted(classes)) or "(none)"
        raise SystemExit(
            f"machine class {want!r} has no entry in {REGISTRY}. Known: {known}")
    declared = entry.get("cores")
    if declared is not None and int(declared) != observed_cores:
        raise SystemExit(
            f"class {want!r} declares {declared} cores; this machine has "
            f"{observed_cores}. Fix the registry before measuring; do not "
            f"relabel the run (#283).")
    return entry


# ---------------------------------------------------------------------------
# The documents, named rather than counted
# ---------------------------------------------------------------------------
def sha256_file(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 16), b""):
            h.update(block)
    return h.hexdigest()


def document_digest(paths: list[pathlib.Path]) -> str:
    """One digest over the set: every name with the hash of its bytes.

    Two runs claiming the same document set can be checked against each other
    with this and nothing else. A file swapped for another of the same name
    moves it, which a count never would.
    """
    h = hashlib.sha256()
    for path in sorted(paths, key=lambda p: p.name):
        h.update(f"{path.name} {sha256_file(path)}\n".encode())
    return h.hexdigest()


def gate_corpus_agrees(repo: pathlib.Path, corpus_dir: pathlib.Path,
                       paths: list[pathlib.Path]) -> str | None:
    """Why the directory is not the gate corpus, or None when it is.

    The manifest pins every entry by SHA-256. Measuring a directory that merely
    looks like the corpus would report a number for a set nobody can reproduce,
    which is the whole reason the manifest exists.
    """
    manifest_path = repo / GATE_MANIFEST
    if not manifest_path.is_file():
        return f"{GATE_MANIFEST} is missing"
    manifest = json.loads(manifest_path.read_text())
    want = {entry["name"]: entry["sha256"] for entry in manifest["entries"]}
    have = {path.name: path for path in paths}
    missing = sorted(set(want) - set(have))
    if missing:
        return (f"{len(missing)} of {len(want)} manifest entries are not in "
                f"{corpus_dir} (first: {missing[0]}); run "
                f"scripts/ci/fetch_gate_corpus.py")
    wrong = [name for name, digest in want.items()
             if sha256_file(have[name]) != digest]
    if wrong:
        return (f"{len(wrong)} file(s) in {corpus_dir} do not match the manifest "
                f"digest (first: {sorted(wrong)[0]})")
    return None


def documents(repo: pathlib.Path, set_name: str,
              corpus_dir: pathlib.Path, limit: int) -> list[pathlib.Path]:
    if not corpus_dir.is_dir():
        raise SystemExit(f"document set {set_name!r}: {corpus_dir} is not a directory")
    paths = sorted(p for p in corpus_dir.iterdir()
                   if p.is_file() and p.suffix.lower() == ".pdf")
    if not paths:
        raise SystemExit(f"document set {set_name!r}: no PDFs in {corpus_dir}")
    if set_name == "gate-corpus":
        complaint = gate_corpus_agrees(repo, corpus_dir, paths)
        if complaint is not None:
            raise SystemExit(f"document set 'gate-corpus': {complaint}")
    return paths[:limit] if limit > 0 else paths


# ---------------------------------------------------------------------------
# Axis 1: performance
# ---------------------------------------------------------------------------
def percentile(values: list[float], p: float) -> float | None:
    """The value at `p` of a sorted sample, or None when there is no sample.

    Index-based and inclusive of the ends, the way `compare.mjs` does it, so the
    two halves of one run do not disagree about what a fifth percentile is.
    """
    if not values:
        return None
    ordered = sorted(values)
    index = min(len(ordered) - 1, int(len(ordered) * p))
    return ordered[index]


def performance_axis(repo: pathlib.Path, paths: list[pathlib.Path],
                     binary: pathlib.Path) -> dict:
    """Open, extract text, save -- per document, in milliseconds.

    One pass per document across many documents rather than many passes over
    one: the spread across real documents is the thing a reader needs, and a
    tight loop on a single file measures the page cache.
    """
    if not binary.is_file():
        return {"status": "skipped",
                "why": f"{binary} was not built; run cargo build --release "
                       f"-p pdfluent --example performance"}
    proc = subprocess.run([str(binary), "--tsv", *[str(p) for p in paths]],
                          capture_output=True, text=True, cwd=repo)
    if proc.returncode != 0:
        return {"status": "skipped",
                "why": f"the performance example exited {proc.returncode}: "
                       f"{proc.stderr.strip()[:200]}"}
    rows, unreadable = [], 0
    for line in proc.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) != 6 or parts[0] == "name":
            continue
        if parts[1] != "ok":
            unreadable += 1
            continue
        rows.append(tuple(float(x) for x in parts[3:6]))
    if not rows:
        return {"status": "skipped",
                "why": f"no document in the set could be opened "
                       f"({unreadable} unreadable)"}
    axis = {
        "status": "measured",
        "documents": len(paths),
        # An unreadable document is a measurement, not an absence: it stays in
        # the denominator and gets counted here by name of its own.
        "unreadable": unreadable,
        "measured_documents": len(rows),
    }
    for index, name in enumerate(("open", "text", "save")):
        sample = [row[index] for row in rows]
        axis[f"{name}_ms"] = {
            "p50": round(percentile(sample, 0.50), 3),
            "p95": round(percentile(sample, 0.95), 3),
        }
    return axis


# ---------------------------------------------------------------------------
# Axes 2 and 3: archiving and accuracy, through compare.mjs
# ---------------------------------------------------------------------------
def tool_version(command: list[str]) -> str | None:
    try:
        proc = subprocess.run(command, capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return None
    text = (proc.stdout + proc.stderr).strip().splitlines()
    return text[0].strip() if text else None


def compare_report(repo: pathlib.Path, corpus_dir: pathlib.Path,
                   converter: pathlib.Path, workdir: pathlib.Path,
                   limit: int) -> tuple[dict | None, str]:
    """Run the shared comparison harness; return its report, or why not."""
    for tool in ("node", "verapdf", "mutool"):
        if shutil.which(tool) is None:
            return None, (f"{tool} is not on PATH. veraPDF judges and mutool "
                          f"reads; neither is ours and neither is optional for "
                          f"these two axes.")
    if not converter.is_file():
        return None, (f"{converter} was not built; run cargo build --release "
                      f"-p pdf-manip --example pdfa_convert_real")
    workdir.mkdir(parents=True, exist_ok=True)
    command = [
        "node", str(repo / "benchmarks" / "pdfa" / "reproduce" / "compare.mjs"),
        "--corpus-dir", str(corpus_dir),
        "--converter", f"{converter} {{in}} {{out}}",
        "--name", "pdfluent",
        "--workdir", str(workdir),
    ]
    if limit > 0:
        command += ["--limit", str(limit)]
    proc = subprocess.run(command, capture_output=True, text=True, cwd=repo)
    report_path = workdir / "compare.json"
    if not report_path.is_file():
        return None, (f"compare.mjs exited {proc.returncode} without writing a "
                      f"report: {proc.stderr.strip()[:300]}")
    return json.loads(report_path.read_text()), ""


def as_percent(fraction: float | None) -> float | None:
    return None if fraction is None else round(100.0 * fraction, 1)


def archiving_axis(report: dict | None, why: str) -> dict:
    """Does the archival copy hold up: conformance, and what it costs on disk.

    A conversion the tool refused, and a validation that did not finish, are
    both counted and neither is a pass. Dropping either lifts the percentage
    without changing the software, which is how a 100% comes about.
    """
    if report is None:
        return {"status": "skipped", "why": why}
    return {
        "status": "measured",
        "profile": report["level"],
        "documents": report["documents"],
        "conversion_failed": report["conversion_failed"],
        "judged": report["judged"],
        "without_verdict": report["without_verdict"],
        "conformant": report["conformant"],
        "conformant_pct": as_percent(
            report["conformant"] / report["judged"] if report["judged"] else None),
        "output_size_pct": as_percent(report["size_ratio_total"]),
        "output_size_median_pct": as_percent(report["size_ratio_median"]),
    }


def accuracy_axis(report: dict | None, why: str) -> dict:
    """Does the document still say what it said, and still look like it did.

    Text is counted by mutool, a reader that is not ours, as a multiset of
    words; the character count sits beside it because a broken word separator
    reads as near-total loss on the word axis while every letter is still there.
    Documents with fewer than MIN_SOURCE_WORDS words are counted apart: on those
    the word measure says nothing, and says it at 100%.
    """
    if report is None:
        return {"status": "skipped", "why": why}
    rows = report.get("rows", [])
    converted = [row for row in rows if row.get("converted")]
    judged, too_short = [], 0
    for row in converted:
        retention = row.get("wordRetention")
        if retention is None:
            continue
        if row.get("sourceWords") is not None and row["sourceWords"] < MIN_SOURCE_WORDS:
            too_short += 1
            continue
        judged.append(retention)
    return {
        "status": "measured",
        "documents_judged": len(judged),
        "too_short_to_judge": too_short,
        "no_source_text": len(converted) - len(judged) - too_short,
        "word_retention_median_pct": as_percent(percentile(judged, 0.50)),
        "word_retention_p5_pct": as_percent(percentile(judged, 0.05)),
        "below_95pct_retention": sum(1 for x in judged if x < 0.95),
        "char_retention_median_pct": as_percent(report["char_retention_median"]),
        "separator_broken": report["separator_broken"],
        "visibly_changed": report["render_pages_changed"],
        "render_dpi": report["render_dpi"],
        "render_pages_per_document": report["render_pages_per_document"],
    }


# ---------------------------------------------------------------------------
# A run
# ---------------------------------------------------------------------------
def git_commit(repo: pathlib.Path) -> str:
    """The commit this run measured.

    It is the commit the two example binaries were built from, recorded so the
    measurement can be checked out again. One honest limit: a run taken on a
    branch names that branch's commit, and a rebase before landing gives the
    same content a new name -- so a run measured mid-review can end up naming a
    commit that no longer resolves. Master takes fast-forwards only, so a run
    taken after the last rebase keeps its name through the landing. Nothing here
    rewrites the field afterwards: a measurement edited by hand is the defect
    this whole programme exists to remove.
    """
    proc = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"],
                          capture_output=True, text=True)
    return proc.stdout.strip() if proc.returncode == 0 else ""


def measure(args: argparse.Namespace) -> int:
    repo = pathlib.Path(args.repo).resolve()
    want = os.environ.get("BENCH_MACHINE_CLASS", "")
    if not want:
        raise SystemExit(
            "BENCH_MACHINE_CLASS is not set. Name the machine class this run "
            "measures; it must be an entry in benchmarks/BASELINE_HARDWARE.toml "
            "(#283).")
    cores = os.cpu_count() or 0
    entry = machine_class(repo, want, cores)

    spec = DOCUMENT_SETS[args.set]
    chosen = args.corpus_dir or spec["default_dir"]
    if not chosen:
        raise SystemExit(f"document set {args.set!r} has no default directory; "
                         f"pass --corpus-dir")
    corpus_dir = pathlib.Path(chosen)
    if not corpus_dir.is_absolute():
        corpus_dir = repo / corpus_dir
    corpus_dir = corpus_dir.resolve()
    paths = documents(repo, args.set, corpus_dir, args.limit)

    today = dt.date.today().isoformat()
    run_id = f"v7-{today}-{want}-{args.set}"
    if not RUN_ID.match(run_id):
        raise SystemExit(f"the run identifier {run_id!r} is not the shape every "
                         f"published figure is resolved through: {RUN_ID.pattern}")

    print(f"  run                {run_id}")
    print(f"  machine class      {want} -- {entry.get('description', 'no description')}")
    print(f"  cores observed     {cores}")
    print(f"  documents          {len(paths)} from {corpus_dir}")

    workdir = pathlib.Path(args.workdir or tempfile.mkdtemp(prefix="v7-"))
    report, why = compare_report(
        repo, corpus_dir, repo / "target" / "release" / "examples" / "pdfa_convert_real",
        workdir, args.limit)
    if report is None:
        print(f"  archiving/accuracy SKIPPED (not a pass): {why}")

    run = {
        "run_id": run_id,
        "date": today,
        "machine_class": want,
        "cores_observed": cores,
        # System and release only. `platform.machine()` reports the
        # INTERPRETER's architecture, which under a translation layer is not
        # the machine's -- and a wrong fact about the hardware is exactly what
        # the machine class exists to replace.
        "kernel": f"{platform.system()} {platform.release()}",
        "commit": git_commit(repo),
        "document_set": {
            "name": args.set,
            "directory": str(corpus_dir),
            "description": spec["description"],
            "licence": spec["licence"],
            "documents": len(paths),
            "digest": document_digest(paths),
        },
        "tools": {
            "verapdf": tool_version(["verapdf", "--version"]),
            "mutool": tool_version(["mutool", "-v"]),
            "node": tool_version(["node", "--version"]),
        },
        "axes": {
            "performance": performance_axis(
                repo, paths,
                repo / "target" / "release" / "examples" / "performance"),
            "archiving": archiving_axis(report, why),
            "accuracy": accuracy_axis(report, why),
        },
    }
    run["axes_skipped"] = sorted(
        name for name, axis in run["axes"].items() if axis["status"] == "skipped")

    out = repo / RUNS_DIR / f"{run_id}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(run, indent=2, sort_keys=True) + "\n")
    print(f"  written            {out.relative_to(repo)}")
    if run["axes_skipped"]:
        print(f"  INCOMPLETE (not a pass): {', '.join(run['axes_skipped'])} "
              f"measured nothing; no figure from this run may be published for them.")
    return 0


# ---------------------------------------------------------------------------
# Publishing: the table, and only the table
# ---------------------------------------------------------------------------
def load_runs(repo: pathlib.Path) -> list[dict]:
    directory = repo / RUNS_DIR
    if not directory.is_dir():
        return []
    runs = []
    for path in sorted(directory.glob("*.json")):
        runs.append(json.loads(path.read_text()))
    return runs


def _cell(value) -> str:
    return "n/a" if value is None else str(value)


def render_table(runs: list[dict]) -> str:
    """The measured section, derived from the run files and nothing else.

    The guard compares this against what stands in the published document, so a
    figure typed in by hand, a figure that outlived the run it came from, and a
    figure for an axis that was skipped all read the same way: a difference.
    """
    lines = [
        "| Run | Machine class | Documents | Axis | Measured |",
        "|---|---|---|---|---|",
    ]
    for run in sorted(runs, key=lambda r: r["run_id"]):
        run_id = run["run_id"]
        machine = run["machine_class"]
        count = run["document_set"]["documents"]
        for axis_name in AXES:
            axis = run.get("axes", {}).get(axis_name)
            if axis is None:
                # Rendered rather than raised: the guard, not this function, is
                # what says a run missing an axis is unusable, and a renderer
                # that dies takes the verdict down with it.
                cell = "ABSENT (not a pass) — the run reports no such axis"
            elif axis["status"] != "measured":
                cell = f"SKIPPED (not a pass) — {axis.get('why', 'no reason recorded')}"
            elif axis_name == "performance":
                cell = "; ".join(
                    f"{op} p50 {_cell(axis[f'{op}_ms']['p50'])} ms, "
                    f"p95 {_cell(axis[f'{op}_ms']['p95'])} ms"
                    for op in ("open", "text", "save"))
                cell += f" (over {axis['measured_documents']} readable, {axis['unreadable']} not)"
            elif axis_name == "archiving":
                cell = (f"PDF/A-{axis['profile']} conformant "
                        f"{axis['conformant']} of {axis['judged']} judged "
                        f"({_cell(axis['conformant_pct'])}%), "
                        f"{axis['conversion_failed']} conversion(s) refused, "
                        f"{axis['without_verdict']} without a verdict; "
                        f"output {_cell(axis['output_size_pct'])}% of input")
            else:
                cell = (f"word retention median "
                        f"{_cell(axis['word_retention_median_pct'])}%, "
                        f"5th percentile {_cell(axis['word_retention_p5_pct'])}% "
                        f"over {axis['documents_judged']} judged "
                        f"({axis['too_short_to_judge']} too short, "
                        f"{axis['no_source_text']} without source text); "
                        f"{axis['below_95pct_retention']} below 95%; "
                        f"{axis['visibly_changed']} visibly changed")
            lines.append(f"| `{run_id}` | {machine} | {count} | {axis_name} | {cell} |")
    return "\n".join(lines)


def publish(args: argparse.Namespace) -> int:
    repo = pathlib.Path(args.repo).resolve()
    runs = load_runs(repo)
    if not runs:
        raise SystemExit(f"there is no run in {RUNS_DIR} to publish from.")
    path = repo / PUBLISHED
    if not path.is_file():
        raise SystemExit(f"{PUBLISHED} is missing; there is nowhere to publish to.")
    text = path.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{PUBLISHED} has no measured section; it needs the "
                         f"{BEGIN} and {END} markers.")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    path.write_text(f"{head}{BEGIN}\n\n{render_table(runs)}\n\n{END}{tail}")
    print(f"  {PUBLISHED} carries {len(runs)} run(s), {len(runs) * len(AXES)} rows")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", default=str(REPO))
    sub = parser.add_subparsers(dest="command", required=True)

    m = sub.add_parser("measure", help="measure one document set")
    m.add_argument("--set", choices=sorted(DOCUMENT_SETS), required=True)
    m.add_argument("--corpus-dir", default=None)
    m.add_argument("--limit", type=int, default=0)
    m.add_argument("--workdir", default=None)
    m.set_defaults(func=measure)

    p = sub.add_parser("publish", help="regenerate the measured table")
    p.set_defaults(func=publish)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
