"""One repeatable programme for the three axes we publish numbers on.

WHY THIS EXISTS

The three axes were each measured by something else. Speed came from
`crates/pdfluent/examples/performance.rs` run by hand on whatever documents
were open at the time (A22). Archiving came from `benchmarks/pdfa/reproduce/`.
Accuracy -- how much of the document survives being touched -- came from the
same place, and from a Python script before that. Three harnesses, three
document sets, three dates, and a buyer comparing us with anyone else has to
reconcile them before they can read a single number.

So this is one programme, one document set at a time, one output file. It does
not re-implement the arithmetic: the archiving and accuracy axes run through
`benchmarks/pdfa/reproduce/compare.mjs`, which is the converter-agnostic harness
#140 delivered and whose sums are covered by `compare.test.mjs` in the gate. What
this adds is the part that was missing -- provenance. Every result says which
machine class it was measured on, which documents by name and digest, which
external tools by version, and which commit of this repository.

WHAT IT REFUSES TO DO

Measure without naming the machine. `BENCH_MACHINE_CLASS` must name an entry in
`benchmarks/BASELINE_HARDWARE.toml` and the cores it declares must be the cores
the machine has, which is the rule `scripts/run_benchmarks.sh` already applies
(#283). A result whose provenance is a literal invites a comparison against
targets measured somewhere else, and that comparison passes.

Report an axis it could not measure as anything but skipped. veraPDF and mutool
are not ours and are not always installed. An axis without them writes
`"status": "skipped"` with the reason and NO numbers, and the guard refuses to
let a skipped axis back a published figure. The alternative -- dropping the axis
and reporting the other two -- is how a partial run reads as a complete one.

THE DOCUMENT SETS

  fixtures     Our own generated fixtures, in the repository, ours to publish.
               Small, fast, and the set that answers "did this change break
               something" rather than "what does the world look like".

  gate-corpus  The 500 PDFs of `corpus/GATE_CORPUS_MANIFEST.json`, fetched from
               pdf.js, PDFBox and the veraPDF corpus at pinned commits under
               Apache-2.0 and CC-BY-4.0. Licence known, provenance recorded, not
               ours, and not committed here (#215). Materialise it first with
               `scripts/ci/fetch_gate_corpus.py`.

Both are named in the result, with a digest over their contents, so two runs
that say they measured the same thing can be checked rather than believed.

USAGE

    BENCH_MACHINE_CLASS=dev-macbook-m1pro \\
      python3 scripts/benchmarks/v7_benchmark.py measure --set fixtures

    BENCH_MACHINE_CLASS=desktop-xfa-fast \\
      python3 scripts/benchmarks/v7_benchmark.py measure \\
        --set gate-corpus --corpus-dir /tmp/gate-corpus

    python3 scripts/benchmarks/v7_benchmark.py publish

`measure` writes `benchmarks/runs/v7/<run-id>.json`. `publish` regenerates the
measured table in `benchmarks/V7_BENCHMARK_PROGRAMME.md` from those files, and
`scripts/ci/a_published_number_names_its_run.py` refuses any published figure
the table does not carry a run for.
"""

