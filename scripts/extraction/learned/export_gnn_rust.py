"""The line graph network's weights as plain Rust constants (#638).

    # after training, once: the weights out of PyTorch into the repository
    ~/.cache/pdfluent/gnn-venv/bin/python export_gnn_rust.py --from-torch /tmp/line-gnn \
        --weights models/line_gnn/weights.json.gz
    # from then on, without torch -- what the reproducibility guard runs
    python3 export_gnn_rust.py --weights models/line_gnn/weights.json.gz \
        --out crates/pdf-engine/src/learned/models/line_gnn

NO RUNTIME, NO FORMAT. The network is a few dense layers and a gather; the
engine multiplies by these arrays itself (`learned::line_gnn`), so it runs in
WASM and in the default build, and nothing is loaded at run time.

ONE FILE UNDER 900 KB EACH, as the repository keeps files under 1 MB: `mod.rs`
carries the shapes and the normalisation, `part_NN.rs` the weight arrays.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import pathlib
import sys

CHUNK_BYTES = 900_000
MARK = "@generated by scripts/extraction/learned/export_gnn_rust.py"
LICENCE = """// Copyright (c) 2026 Innovation Trigger B.V.
//
// PDFluent is available under two licences, at your option: the GNU AGPLv3, or
// the PDFluent Commercial Licence. See the LICENSE file in this repository --
// that file travels with the copy you received, which a URL does not.
"""


def from_torch(src: pathlib.Path, weights: pathlib.Path) -> None:
    """state_dict + config + normalisation -> one deterministic JSON."""
    import numpy as np
    import torch
    cfg = json.loads((src / "config.json").read_text())
    state = torch.load(src / "line_gnn.pt", map_location="cpu")
    norm = np.load(src / "norm.npz")
    # THE SHORTEST TEXT THAT IS STILL THE SAME f32: numpy's repr of a float32
    # round-trips, and it is half the length of the double it would print as.
    short = lambda xs: [float(repr(np.float32(x))) for x in xs]
    out = {"config": cfg,
           "norm": {k: short(norm[k].astype(np.float32).tolist()) for k in ("mx", "sx", "me", "se")},
           "tensors": {k: {"shape": list(v.shape), "values": short(v.flatten().tolist())}
                       for k, v in sorted(state.items())}}
    weights.parent.mkdir(parents=True, exist_ok=True)
    with open(weights, "wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", mtime=0, filename="") as gz:
        gz.write((json.dumps(out, sort_keys=True) + "\n").encode())


def rust_name(key: str) -> str:
    return key.replace(".", "_").upper()


def f32(v: float) -> str:
    # The weights file already holds each value as the shortest decimal that
    # is its f32; printed as that decimal it parses back to the same bits.
    text = repr(float(v))
    return (text if ("." in text or "e" in text or "inf" in text or "nan" in text) else text + ".0") + "_f32"


def export(weights_bytes: bytes) -> dict[str, str]:
    """The files of the model directory, by name."""
    data = json.loads(gzip.decompress(weights_bytes))
    cfg, norm, tensors = data["config"], data["norm"], data["tensors"]
    sha = hashlib.sha256(gzip.decompress(weights_bytes)).hexdigest()
    params = sum(len(t["values"]) for t in tensors.values())
    head = [f"// {MARK} -- do not edit.", "//", LICENCE.rstrip("\n"),
            f"//! The `line_gnn` network: {params} parameters, hidden {cfg['hidden']}, "
            f"{cfg['layers']} layers, {len(cfg['directions'])} edge directions.",
            "//!", f"//! Weights sha256 (of weights.json): {sha}", ""]
    parts: list[list[str]] = [[]]
    size = 0
    for key, t in sorted(tensors.items()):
        values = t["values"]
        # A WEIGHT MATRIX IS WRITTEN COLUMN BY COLUMN (transposed): the engine
        # adds one column per input, a loop the compiler vectorises, where a
        # row-by-row dot product is a chain of additions it may not reorder.
        if key.endswith(".weight") and len(t["shape"]) == 2:
            rows, cols = t["shape"]
            values = [values[r * cols + c] for c in range(cols) for r in range(rows)]
        body = ", ".join(f32(v) for v in values)
        text = f"pub static {rust_name(key)}: [f32; {len(t['values'])}] = [{body}];\n"
        if size + len(text) > CHUNK_BYTES and parts[-1]:
            parts.append([]); size = 0
        parts[-1].append(text); size += len(text)
    files = {}
    mods = []
    for i, texts in enumerate(parts):
        name = f"part_{i:02d}"
        mods.append(name)
        files[f"{name}.rs"] = "\n".join(
            [f"// {MARK} -- do not edit.", "//", LICENCE.rstrip("\n"), "",
             "#![allow(clippy::excessive_precision, clippy::approx_constant)]", ""]) + "".join(texts)
    lines = head + [f"mod {m};" for m in mods] + [""]
    for m in mods:
        lines.append(f"pub use {m}::*;")
    lines += ["",
              "/// The sha256 of the weights this code was generated from.",
              f'pub const WEIGHTS_SHA256: &str = "{sha}";',
              f"pub const HIDDEN: usize = {cfg['hidden']};",
              f"pub const LAYERS: usize = {cfg['layers']};",
              f"pub const NODE_WIDTH: usize = {cfg['node_width']};",
              f"pub const EDGE_WIDTH: usize = {cfg['edge_width']};",
              f"pub const DIRECTIONS: [&str; {len(cfg['directions'])}] = [{', '.join(repr(d).replace(chr(39), chr(34)) for d in cfg['directions'])}];",
              f"pub const CLASSES: [&str; {len(cfg['classes'])}] = [{', '.join(repr(c).replace(chr(39), chr(34)) for c in cfg['classes'])}];",
              "/// The input groups past the base row, in the order the node row",
              "/// carries them (`train_line_gnn.GROUP_ORDER`); empty for a network",
              "/// trained on the base row alone.",
              f"pub const GROUPS: [&str; {len(cfg.get('groups', []))}] = [{', '.join(repr(g).replace(chr(39), chr(34)) for g in cfg.get('groups', []))}];",
              "/// The training pages' mean and spread of every node and edge input:",
              "/// the network reads `(x - MEAN) / SPREAD`.",
              f"pub static NODE_MEAN: [f32; {len(norm['mx'])}] = [{', '.join(f32(v) for v in norm['mx'])}];",
              f"pub static NODE_SPREAD: [f32; {len(norm['sx'])}] = [{', '.join(f32(v) for v in norm['sx'])}];",
              f"pub static EDGE_MEAN: [f32; {len(norm['me'])}] = [{', '.join(f32(v) for v in norm['me'])}];",
              f"pub static EDGE_SPREAD: [f32; {len(norm['se'])}] = [{', '.join(f32(v) for v in norm['se'])}];",
              ""]
    files["mod.rs"] = "\n".join(lines)
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--from-torch", type=pathlib.Path)
    ap.add_argument("--weights", type=pathlib.Path, required=True)
    ap.add_argument("--out", type=pathlib.Path)
    args = ap.parse_args()
    if args.from_torch:
        from_torch(args.from_torch, args.weights)
        print(f"[gnn-export] weights written to {args.weights}")
    if args.out:
        args.out.mkdir(parents=True, exist_ok=True)
        for old in args.out.glob("*.rs"):
            old.unlink()
        files = export(args.weights.read_bytes())
        for name, text in files.items():
            (args.out / name).write_text(text)
        print(f"[gnn-export] {args.out}: {len(files)} file(s), "
              f"{sum(len(t) for t in files.values())} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
