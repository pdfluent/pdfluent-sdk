"""Compile a LightGBM tree dump to plain Rust (#598).

    python3 scripts/extraction/learned/export_rust.py \
        --model scripts/extraction/learned/models/toy_heading/model.json \
        --out crates/pdf-learned/src/models/toy_heading.rs

Our own exporter, because m2cgen has not been released since 2022 and the
output here has to meet this repository's rules: no runtime dependency, no
allocation per prediction, no unsafe, and a header that names the model it came
from by hash. The path it writes to is the caller's -- the lanes that own a
decision put its model beside the code that makes it.

WHAT IS EXACT

The margin. A split is LightGBM's own numerical decision, missing values
included: with missing_type NaN a NaN goes the default way; with Zero a zero or
a NaN does; with None a NaN is read as 0.0 and compared. Thresholds are written
with Python's shortest round-trip repr, which Rust parses to the same f64, and
the sum is taken tree by tree in LightGBM's order. The parity test holds the
generated code to LightGBM's own margins within 1e-6.

Categorical splits are refused rather than approximated: nothing trains with
them yet, and a silently wrong branch is the failure this file exists to rule
out.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import pathlib

HEADER = """// @generated by scripts/extraction/learned/export_rust.py -- do not edit.
//
// Copyright (c) 2026 Innovation Trigger B.V.
//
// PDFluent is available under two licences, at your option: the GNU AGPLv3, or
// the PDFluent Commercial Licence. See the LICENSE file in this repository --
// that file travels with the copy you received, which a URL does not.
"""

MISSING = {"None": 0, "Zero": 1, "NaN": 2}


def rust_float(value: float) -> str:
    text = repr(float(value))
    if text in ("inf", "-inf", "nan"):
        return {"inf": "f64::INFINITY", "-inf": "f64::NEG_INFINITY", "nan": "f64::NAN"}[text]
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "_f64"


def node_code(node: dict, depth: int, stats: dict) -> str:
    pad = "    " * depth
    if "leaf_value" in node:
        return f"{pad}{rust_float(node['leaf_value'])}\n"
    if node.get("decision_type") != "<=":
        raise SystemExit(f"unsupported decision type {node.get('decision_type')!r} "
                         "(categorical splits are refused, not approximated)")
    stats["splits"] += 1
    stats["depth"] = max(stats["depth"], depth)
    goes_left = (f"go_left(x[{node['split_feature']}], {rust_float(node['threshold'])}, "
                 f"{'true' if node['default_left'] else 'false'}, {MISSING[node['missing_type']]})")
    return (f"{pad}if {goes_left} {{\n"
            + node_code(node["left_child"], depth + 1, stats)
            + f"{pad}}} else {{\n"
            + node_code(node["right_child"], depth + 1, stats)
            + f"{pad}}}\n")


def classes_of(model: dict) -> int:
    """How many classes the model predicts, 1 for a binary or regression one.

    WHY THIS IS ASKED EVERYWHERE BELOW. LightGBM writes a multiclass model as
    ONE flat list of trees in which tree `i` belongs to class `i % num_class`.
    Summing that list gives a number that is not any class's margin and not an
    error either -- it is a plausible-looking float, and a model exported that
    way predicts confident nonsense with nothing to show for it. So the count
    is read from the dump and the single-margin path REFUSES a model with more
    than one class rather than quietly averaging them (T4, #600).
    """
    return int(model.get("num_class") or 1)


def export(model_bytes: bytes, name: str) -> tuple[str, dict]:
    model = json.loads(model_bytes)
    if classes_of(model) > 1:
        raise SystemExit(
            f"export: this model has {classes_of(model)} classes and "
            f"`predict_margin` returns one number. Use --classes to write "
            f"`predict_margins`, which returns one margin per class. Summing "
            f"the trees of a multiclass model is not an approximation of "
            f"anything -- tree i belongs to class i % num_class.")
    features = model["feature_names"]
    n = len(features)
    digest = hashlib.sha256(model_bytes).hexdigest()
    stats = {"splits": 0, "depth": 0, "trees": len(model["tree_info"])}
    trees = []
    for i, tree in enumerate(model["tree_info"]):
        body = node_code(tree["tree_structure"], 1, stats)
        trees.append(f"#[allow(clippy::excessive_precision, clippy::unreadable_literal)]\n"
                     f"fn tree_{i}(x: &[f64; {n}]) -> f64 {{\n{body}}}\n")
    names = ", ".join(json.dumps(f) for f in features)
    calls = " + ".join(f"tree_{i}(x)" for i in range(len(trees))) or "0.0"
    code = (HEADER
            + f"//! The `{name}` model: {stats['trees']} trees, {stats['splits']} splits, "
              f"depth at most {stats['depth']}.\n"
            + "//!\n"
            + f"//! Model sha256 (of model.json): {digest}\n\n"
            + f"/// The sha256 of the LightGBM dump this code was generated from.\n"
            + f"pub const MODEL_SHA256: &str = \"{digest}\";\n\n"
            + f"/// The input, in order: `x[i]` is `FEATURES[i]`, NaN when missing.\n"
            + f"pub const FEATURES: [&str; {n}] = [{names}];\n\n"
            + "/// LightGBM's numerical decision, missing values included.\n"
            + "#[inline(always)]\n"
            + "fn go_left(value: f64, threshold: f64, default_left: bool, missing: u8) -> bool {\n"
            + "    // 0: None, 1: Zero, 2: NaN -- LightGBM's MissingType.\n"
            + "    let value = if missing != 2 && value.is_nan() { 0.0 } else { value };\n"
            + "    if (missing == 1 && value.abs() <= 1e-35) || (missing == 2 && value.is_nan()) {\n"
            + "        return default_left;\n"
            + "    }\n"
            + "    value <= threshold\n"
            + "}\n\n"
            + "/// The raw margin: the sum of the trees, before the sigmoid.\n"
            + f"pub fn predict_margin(x: &[f64; {n}]) -> f64 {{\n    {calls}\n}}\n\n"
            + "\n".join(trees))
    return code, stats


def export_multiclass(model_bytes: bytes, name: str) -> tuple[str, dict]:
    """A multiclass model as `predict_margins` returning one margin per class.

    The trees are LightGBM's flat list; tree `i` scores class `i % num_class`,
    and the margins come back in class order. The softmax is NOT applied here:
    the parity test compares margins, which is where a difference would show
    up undamped, and the caller that wants probabilities says so.
    """
    model = json.loads(model_bytes)
    features = model["feature_names"]
    n = len(features)
    k = classes_of(model)
    digest = hashlib.sha256(model_bytes).hexdigest()
    stats = {"splits": 0, "depth": 0, "trees": len(model["tree_info"]),
             "classes": k}
    trees = []
    for i, tree in enumerate(model["tree_info"]):
        body = node_code(tree["tree_structure"], 1, stats)
        trees.append(f"#[allow(clippy::excessive_precision, clippy::unreadable_literal)]\n"
                     f"fn tree_{i}(x: &[f64; {n}]) -> f64 {{\n{body}}}\n")
    per_class = []
    for c in range(k):
        mine = [i for i in range(len(trees)) if i % k == c]
        calls = " + ".join(f"tree_{i}(x)" for i in mine) or "0.0"
        per_class.append(f"        {calls},")
    names = ", ".join(json.dumps(f) for f in features)
    code = (HEADER
            + f"//! The `{name}` model: {stats['trees']} trees, {stats['splits']} "
              f"splits, depth at most {stats['depth']}.\n"
            + f"//!\n"
            + f"//! Every one of those trees runs on every prediction: the {k} "
              f"classes share one flat list and tree i scores class i % {k}.\n"
            + "//!\n"
            + f"//! Model sha256 (of model.json): {digest}\n\n"
            + f"/// The sha256 of the LightGBM dump this code was generated from.\n"
            + f"pub const MODEL_SHA256: &str = \"{digest}\";\n\n"
            + f"/// The input, in order: `x[i]` is `FEATURES[i]`, NaN when missing.\n"
            + f"pub const FEATURES: [&str; {n}] = [{names}];\n\n"
            + f"/// How many classes [`predict_margins`] returns.\n"
            + f"pub const CLASSES: usize = {k};\n\n"
            + "/// LightGBM's numerical decision, missing values included.\n"
            + "#[inline(always)]\n"
            + "fn go_left(value: f64, threshold: f64, default_left: bool, missing: u8) -> bool {\n"
            + "    // 0: None, 1: Zero, 2: NaN -- LightGBM's MissingType.\n"
            + "    let value = if missing != 2 && value.is_nan() { 0.0 } else { value };\n"
            + "    if (missing == 1 && value.abs() <= 1e-35) || (missing == 2 && value.is_nan()) {\n"
            + "        return default_left;\n"
            + "    }\n"
            + "    value <= threshold\n"
            + "}\n\n"
            + "/// The raw margins, one per class, before any softmax.\n"
            + f"pub fn predict_margins(x: &[f64; {n}]) -> [f64; {k}] {{\n    [\n"
            + "\n".join(per_class)
            + "\n    ]\n}\n\n"
            + "\n".join(trees))
    return code, stats


# The repository keeps every file under 1 MB (scripts/ci/check_large_blobs.sh),
# and a model of several hundred trees is several MB of Rust. So a large model
# is written as a directory: `mod.rs` with the header, the features, the
# threshold and `predict_margin`, and `part_NN.rs` files of whole trees, each
# kept under this many bytes (#599).
CHUNK_BYTES = 900_000


def export_multiclass_chunked(model_bytes: bytes, name: str,
                              chunk_bytes: int = CHUNK_BYTES
                              ) -> tuple[dict[str, str], dict]:
    """A large multiclass model as a directory, one accumulator per class.

    ONE ACCUMULATOR PER CLASS, CARRIED THROUGH THE PARTS. Each part adds its
    own trees to the class each belongs to, and the array of accumulators is
    passed on -- so the additions happen in LightGBM's order within a class,
    which is what the parity test asks for, and no class's trees are ever
    added to another's.
    """
    model = json.loads(model_bytes)
    features = model["feature_names"]
    n = len(features)
    k = classes_of(model)
    digest = hashlib.sha256(model_bytes).hexdigest()
    stats = {"splits": 0, "depth": 0, "trees": len(model["tree_info"]),
             "classes": k}
    parts: list[list[tuple[int, str]]] = [[]]
    size = 0
    for i, tree in enumerate(model["tree_info"]):
        body = node_code(tree["tree_structure"], 1, stats)
        code = (f"#[allow(clippy::excessive_precision, clippy::unreadable_literal)]\n"
                f"fn tree_{i}(x: &[f64; {n}]) -> f64 {{\n{body}}}\n")
        if parts[-1] and size + len(code.encode()) > chunk_bytes:
            parts.append([])
            size = 0
        parts[-1].append((i, code))
        size += len(code.encode())
    files: dict[str, str] = {}
    for p, trees in enumerate(parts):
        adds = "".join(f"    acc[{i % k}] += tree_{i}(x);\n" for i, _ in trees)
        files[f"part_{p:02d}.rs"] = (
            HEADER
            + f"//! Trees {trees[0][0]} to {trees[-1][0]} of the `{name}` model "
              f"(model sha256 {digest}).\n\n"
            + "use super::go_left;\n\n"
            + "/// Adds these trees to their own class's accumulator.\n"
            + f"pub(super) fn add(x: &[f64; {n}], mut acc: [f64; {k}]) -> [f64; {k}] {{\n"
            + adds + "    acc\n}\n\n"
            + "\n".join(code for _, code in trees))
    names = ", ".join(json.dumps(f) for f in features)
    mods = "".join(f"mod part_{p:02d};\n" for p in range(len(parts)))
    chain = ("".join(f"    let acc = part_{p:02d}::add(x, acc);\n"
                     for p in range(len(parts) - 1))
             + f"    part_{len(parts) - 1:02d}::add(x, acc)\n")
    files["mod.rs"] = (
        HEADER
        + f"//! The `{name}` model: {stats['trees']} trees, {stats['splits']} "
          f"splits, depth at most {stats['depth']}, in {len(parts)} part(s).\n"
        + "//!\n"
        + f"//! Every one of those trees runs on every prediction: the {k} "
          f"classes share one flat list and tree i scores class i % {k}.\n"
        + "//!\n"
        + f"//! Model sha256 (of model.json): {digest}\n\n"
        + mods + "\n"
        + "/// The sha256 of the LightGBM dump this code was generated from.\n"
        + f"pub const MODEL_SHA256: &str = \"{digest}\";\n\n"
        + "/// The input, in order: `x[i]` is `FEATURES[i]`, NaN when missing.\n"
        + f"pub const FEATURES: [&str; {n}] = [{names}];\n\n"
        + "/// How many classes [`predict_margins`] returns.\n"
        + f"pub const CLASSES: usize = {k};\n\n"
        + "/// LightGBM's numerical decision, missing values included.\n"
        + "#[inline(always)]\n"
        + "fn go_left(value: f64, threshold: f64, default_left: bool, missing: u8) -> bool {\n"
        + "    // 0: None, 1: Zero, 2: NaN -- LightGBM's MissingType.\n"
        + "    let value = if missing != 2 && value.is_nan() { 0.0 } else { value };\n"
        + "    if (missing == 1 && value.abs() <= 1e-35) || (missing == 2 && value.is_nan()) {\n"
        + "        return default_left;\n"
        + "    }\n"
        + "    value <= threshold\n"
        + "}\n\n"
        + "/// The raw margins, one per class, before any softmax.\n"
        + f"pub fn predict_margins(x: &[f64; {n}]) -> [f64; {k}] {{\n"
        + f"    let acc = [0.0f64; {k}];\n{chain}}}\n")
    stats["parts"] = len(parts)
    return files, stats




def read_model(path: pathlib.Path) -> bytes:
    """The dump's JSON bytes; a `.json.gz` is read through gzip, so its digest
    is the digest of the JSON and not of one particular compression of it."""
    raw = path.read_bytes()
    return gzip.decompress(raw) if path.suffix == ".gz" else raw


def export_chunked(model_bytes: bytes, name: str, threshold: float,
                   chunk_bytes: int = CHUNK_BYTES) -> tuple[dict[str, str], dict]:
    """A large model as a directory of files, each under `chunk_bytes`.

    THE SUM IS LIGHTGBM'S, TERM FOR TERM. The trees are added in LightGBM's
    order into one accumulator that is carried through the parts -- a partial
    sum per part would regroup the additions and move the margin in the last
    bits, which the parity test would then have to forgive.
    """
    model = json.loads(model_bytes)
    if classes_of(model) > 1:
        raise SystemExit(
            f"export: this model has {classes_of(model)} classes. Use "
            f"--classes with --threshold, which writes one accumulator per "
            f"class; one accumulator would add class 0's trees to class 1's.")
    features = model["feature_names"]
    n = len(features)
    digest = hashlib.sha256(model_bytes).hexdigest()
    stats = {"splits": 0, "depth": 0, "trees": len(model["tree_info"])}
    parts: list[list[tuple[int, str]]] = [[]]
    size = 0
    for i, tree in enumerate(model["tree_info"]):
        body = node_code(tree["tree_structure"], 1, stats)
        code = (f"#[allow(clippy::excessive_precision, clippy::unreadable_literal)]\n"
                f"fn tree_{i}(x: &[f64; {n}]) -> f64 {{\n{body}}}\n")
        if parts[-1] and size + len(code.encode()) > chunk_bytes:
            parts.append([])
            size = 0
        parts[-1].append((i, code))
        size += len(code.encode())
    files: dict[str, str] = {}
    for p, trees in enumerate(parts):
        adds = "".join(f"    acc += tree_{i}(x);\n" for i, _ in trees)
        files[f"part_{p:02d}.rs"] = (
            HEADER
            + f"//! Trees {trees[0][0]} to {trees[-1][0]} of the `{name}` model (model sha256 {digest}).\n\n"
            + "use super::go_left;\n\n"
            + f"/// Adds these trees to `acc`, in LightGBM's order.\n"
            + f"pub(super) fn add(x: &[f64; {n}], mut acc: f64) -> f64 {{\n{adds}    acc\n}}\n\n"
            + "\n".join(code for _, code in trees))
    names = ", ".join(json.dumps(f) for f in features)
    mods = "".join(f"mod part_{p:02d};\n" for p in range(len(parts)))
    chain = ("".join(f"    let acc = part_{p:02d}::add(x, acc);\n" for p in range(len(parts) - 1))
             + f"    part_{len(parts) - 1:02d}::add(x, acc)\n")
    files["mod.rs"] = (
        HEADER
        + f"//! The `{name}` model: {stats['trees']} trees, {stats['splits']} splits, "
          f"depth at most {stats['depth']}, in {len(parts)} part(s).\n"
        + "//!\n"
        + f"//! Model sha256 (of model.json): {digest}\n\n"
        + mods + "\n"
        + "/// The sha256 of the LightGBM dump this code was generated from.\n"
        + f"pub const MODEL_SHA256: &str = \"{digest}\";\n\n"
        + "/// The input, in order: `x[i]` is `FEATURES[i]`, NaN when missing.\n"
        + f"pub const FEATURES: [&str; {n}] = [{names}];\n\n"
        + "/// The probability at or above which the decision is taken, chosen on the\n"
        + "/// validation documents and recorded in the model's manifest.\n"
        + f"pub const THRESHOLD: f64 = {rust_float(threshold)};\n\n"
        + "/// LightGBM's numerical decision, missing values included.\n"
        + "#[inline(always)]\n"
        + "fn go_left(value: f64, threshold: f64, default_left: bool, missing: u8) -> bool {\n"
        + "    // 0: None, 1: Zero, 2: NaN -- LightGBM's MissingType.\n"
        + "    let value = if missing != 2 && value.is_nan() { 0.0 } else { value };\n"
        + "    if (missing == 1 && value.abs() <= 1e-35) || (missing == 2 && value.is_nan()) {\n"
        + "        return default_left;\n"
        + "    }\n"
        + "    value <= threshold\n"
        + "}\n\n"
        + "/// The raw margin: the sum of the trees, before the sigmoid.\n"
        + f"pub fn predict_margin(x: &[f64; {n}]) -> f64 {{\n    let acc = 0.0;\n{chain}}}\n")
    stats["parts"] = len(parts)
    return files, stats


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--model", required=True, type=pathlib.Path)
    ap.add_argument("--out", required=True, type=pathlib.Path,
                    help="a .rs file, or with --threshold a directory of parts")
    ap.add_argument("--name", default=None)
    ap.add_argument("--threshold", type=float, default=None,
                    help="write the model as a directory of parts with this decision threshold")
    ap.add_argument("--chunked", action="store_true",
                    help="write a directory of parts, each under 900 KB, "
                         "because the repository keeps files under 1 MB")
    ap.add_argument("--classes", action="store_true",
                    help="write `predict_margins` (one margin per class) "
                         "instead of `predict_margin`")
    args = ap.parse_args()
    raw = read_model(args.model)
    name = args.name or args.model.parent.name
    if args.threshold is not None or (args.classes and args.chunked):
        files, stats = (export_multiclass_chunked(raw, name) if args.classes
                        else export_chunked(raw, name, args.threshold))
        args.out.mkdir(parents=True, exist_ok=True)
        for old in args.out.glob("part_*.rs"):
            old.unlink()
        for filename, code in files.items():
            (args.out / filename).write_text(code)
        total = sum(len(c.encode()) for c in files.values())
        print(f"{args.out}/: {stats['trees']} trees"
              + (f" over {stats['classes']} classes" if args.classes else "")
              + f" in {stats['parts']} part(s), {stats['splits']} splits, "
                f"depth {stats['depth']}, {total} bytes")
        return 0
    code, stats = export_multiclass(raw, name) if args.classes else export(raw, name)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(code)
    print(f"{args.out}: {stats['trees']} trees"
          + (f" over {stats['classes']} classes" if args.classes else "")
          + f", {stats['splits']} splits, depth {stats['depth']}, "
            f"{len(code.encode())} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
