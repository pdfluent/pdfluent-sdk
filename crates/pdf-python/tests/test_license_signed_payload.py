# ---------------------------------------------------------------------------
# Subprocess helper — run a snippet in a fresh Python process to avoid
# OnceLock contamination from other test modules.
# ---------------------------------------------------------------------------

def _run_snippet(snippet: str) -> "subprocess.CompletedProcess[str]":
    """Run *snippet* in a clean interpreter and return the CompletedProcess."""
    return subprocess.run(
        [sys.executable, "-c", textwrap.dedent(snippet)],
        capture_output=True,
        text=True,
    )


