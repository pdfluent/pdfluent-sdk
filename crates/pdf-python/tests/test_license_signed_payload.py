class TestSignedPayloadHappyPath:
    """Successful activation and idempotency."""

    def test_valid_payload_activates_developer_tier(self) -> None:
        result = _run_snippet(f"""
            from pdfluent._native import (
                set_license_public_key, set_license_payload, native_license_info
            )
            set_license_public_key(bytes.fromhex("{PUBLIC_KEY_HEX}"))
            set_license_payload({VALID_PAYLOAD!r})
            info = native_license_info()
            # xfa-license Basic → pdfluent Developer
            assert info.tier == "developer", f"expected developer, got {{info.tier}}"
            assert info.output_is_marked is False
        """)
        assert result.returncode == 0, result.stderr

    def test_valid_payload_idempotent(self) -> None:
        result = _run_snippet(f"""
            from pdfluent._native import (
                set_license_public_key, set_license_payload, native_license_info
            )
            set_license_public_key(bytes.fromhex("{PUBLIC_KEY_HEX}"))
            set_license_payload({VALID_PAYLOAD!r})
            set_license_payload({VALID_PAYLOAD!r})  # must not raise
            assert native_license_info().tier == "developer"
        """)
        assert result.returncode == 0, result.stderr

    def test_auto_detect_via_set_license_key(self) -> None:
        result = _run_snippet(f"""
            from pdfluent._native import (
                set_license_public_key, set_license_key, native_license_info
            )
            set_license_public_key(bytes.fromhex("{PUBLIC_KEY_HEX}"))
            set_license_key({VALID_PAYLOAD!r})   # auto-routes JSON → set_license_payload
            assert native_license_info().tier == "developer"
        """)
        assert result.returncode == 0, result.stderr


class TestErrorCodeAttributes:
    """All errors from set_license_payload carry .code and .message."""

    def test_expired_error_has_code_attribute(self) -> None:
        result = _run_snippet(f"""
            from pdfluent._native import set_license_public_key, set_license_payload, PdfluentLicenseError
            set_license_public_key(bytes.fromhex("{PUBLIC_KEY_HEX}"))
            try:
                set_license_payload({EXPIRED_PAYLOAD!r})
            except PdfluentLicenseError as e:
                assert hasattr(e, "code"), "missing .code"
                assert hasattr(e, "message"), "missing .message"
                assert isinstance(e.code, str)
                assert e.code.startswith("E-LICENSE-")
        """)
        assert result.returncode == 0, result.stderr

    def test_invalid_signature_error_has_code_attribute(self) -> None:
        result = _run_snippet(f"""
            from pdfluent._native import set_license_public_key, set_license_payload, PdfluentLicenseError
            set_license_public_key(bytes.fromhex("{PUBLIC_KEY_HEX}"))
            try:
                set_license_payload({WRONG_KEY_PAYLOAD!r})
            except PdfluentLicenseError as e:
                assert hasattr(e, "code"), "missing .code"
                assert e.code == "E-LICENSE-INVALID-SIGNATURE"
        """)
        assert result.returncode == 0, result.stderr
