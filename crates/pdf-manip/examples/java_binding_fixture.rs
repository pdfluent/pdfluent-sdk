//! Generate the fixture the Java binding tests read.
//!
//! `crates/pdf-java/src/test/resources/sample.pdf` used to be a LiveCycle form
//! from a corpus we hold but have no right to redistribute, in a tree that is
//! going public (#310). Nothing in `PdfDocumentTest` needs a form: it opens the
//! file, asks for a page count above zero, wants non-blank text on page 0, wants
//! Producer or Creator to be set, and wants `validatePdfA` to return a report.
//! A one-page document with a line of text answers all five.
//!
//! # Why this is a program and not a committed blob
//!
//! The file IS committed -- `mvn test` has to keep working without a Rust step
//! having run first. This program is what gives it provenance, and
//! `scripts/ci/the_java_fixture_is_the_one_we_generate.py` runs it and compares
//! byte for byte, so the file and the code that explains it cannot drift apart.
//!
//! # Determinism
//!
//! Every field a PDF writer normally fills from the clock or from entropy is
//! pinned here: `/CreationDate`, `/ModDate` and both halves of `/ID`. They are
//! not normalised away at comparison time on purpose -- the bytes most likely
//! to drift are exactly the ones a lenient comparison stops reading.

